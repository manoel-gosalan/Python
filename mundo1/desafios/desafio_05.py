# --------------------------------------------------
# ? Objetivo
# Ler um número inteiro e mostrar seu antecessor e sucessor
# --------------------------------------------------

n1 = int(input("Digite um número interio: "))

# ? Exibição principal
print(f"O número digitado foi: {n1}")

# ? Cálculo do antecessor e sucessor
print(f"O antecessor de {n1} é: {n1 -1}")
# ? Cálculo do sucessor
print(f"O sucessor de {n1} é: {n1 + 1}")

