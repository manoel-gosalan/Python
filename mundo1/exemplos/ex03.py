# ==================================================
# ! OPERADORES RELACIONAIS
# ==================================================

idade = 18
altura = 1.80

# --------------------------------------------------
# ? Maior que >
# --------------------------------------------------
print(idade > 17)

# --------------------------------------------------
# ? Menor que <
# --------------------------------------------------
print(idade < 18)

# --------------------------------------------------
# ? Maior ou igual >=
# --------------------------------------------------
print(idade >= 18)

# --------------------------------------------------
# ? Menor ou igual <=
# --------------------------------------------------
print(idade <= 17)

# --------------------------------------------------
# ? Igualdade ==
# Verifica se os valores são iguais
# --------------------------------------------------
print(idade == 18)

# --------------------------------------------------
# ? Diferença !=
# Verifica se os valores são diferentes
# --------------------------------------------------
print(idade != 18)

# NOTE:
# Operadores relacionais retornam:
# True  -> verdadeiro
# False -> falso

print(altura > 1.70)
print(altura < 1.50)