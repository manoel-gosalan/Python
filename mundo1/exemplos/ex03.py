# ==================================================
# ! OPERADORES ARITMÉTICOS
# ==================================================

numero_1 = 10
numero_2 = 5

# --------------------------------------------------
# ? Adição
# Soma os valores
# --------------------------------------------------
print(numero_1 + numero_2)

# --------------------------------------------------
# ? Subtração
# Remove um valor do outro
# --------------------------------------------------
print(numero_1 - numero_2)

# --------------------------------------------------
# ? Multiplicação
# Multiplica os números
# --------------------------------------------------
print(numero_1 * numero_2)

# --------------------------------------------------
# ? Divisão
# Sempre retorna float
# --------------------------------------------------
print(numero_1 / numero_2)

# NOTE: Mesmo que o resultado seja inteiro,
# a divisão normal retorna float
print(10 / 2)

# --------------------------------------------------
# ? Divisão Inteira //
# Remove as casas decimais
# --------------------------------------------------
print(10 // 3)

# --------------------------------------------------
# ? Potência **
# 2 elevado a 3
# --------------------------------------------------
print(2 ** 3)

# --------------------------------------------------
# ? Resto da Divisão %
# Muito usado para descobrir:
# - números pares
# - números ímpares
# --------------------------------------------------
print(10 % 3)

